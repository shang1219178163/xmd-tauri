/** PowerPoint (.pptx) export using pptxgenjs. */
import PptxGenJS from 'pptxgenjs'
import type { Topic, Workbook } from '@shared/types'

interface BulletItem {
  text: string
  options: {
    bullet: boolean
    indentLevel: number
  }
}

function collectBullets(topic: Topic, depth = 0): BulletItem[] {
  const items: BulletItem[] = []
  for (const child of topic.children?.attached ?? []) {
    items.push({
      text: child.title || 'Untitled',
      options: { bullet: true, indentLevel: Math.min(4, depth) }
    })
    items.push(...collectBullets(child, depth + 1))
  }
  return items
}

async function toBytes(output: string | ArrayBuffer | Blob | Uint8Array): Promise<Uint8Array> {
  if (output instanceof Uint8Array) return output
  if (output instanceof ArrayBuffer) return new Uint8Array(output)
  if (ArrayBuffer.isView(output)) {
    return new Uint8Array(output.buffer, output.byteOffset, output.byteLength)
  }
  if (typeof Blob !== 'undefined' && output instanceof Blob) {
    return new Uint8Array(await output.arrayBuffer())
  }
  throw new Error('PPTX 导出返回了不支持的数据格式')
}

/** Build a presentation: a title slide plus one slide per main topic. */
export async function workbookToPptx(workbook: Workbook): Promise<Uint8Array> {
  const pptx = new PptxGenJS()
  pptx.layout = 'LAYOUT_WIDE'
  pptx.author = 'xmd'
  pptx.company = 'xmd'

  const firstSheet = workbook.sheets[0]
  const title = firstSheet?.rootTopic.title || firstSheet?.title || 'Mind Map'
  pptx.title = title

  const titleSlide = pptx.addSlide()
  titleSlide.background = { color: 'FFFFFF' }
  titleSlide.addText(title, {
    x: 0.6,
    y: 2.1,
    w: 12.1,
    h: 1.2,
    fontSize: 38,
    bold: true,
    align: 'center',
    color: '1F2937'
  })
  titleSlide.addText('Generated by xmd', {
    x: 0.6,
    y: 3.45,
    w: 12.1,
    h: 0.5,
    fontSize: 14,
    align: 'center',
    color: '64748B'
  })

  for (const sheet of workbook.sheets) {
    const mainTopics = sheet.rootTopic.children?.attached ?? []
    for (const mainTopic of mainTopics) {
      const slide = pptx.addSlide()
      slide.addText(mainTopic.title || 'Untitled', {
        x: 0.55,
        y: 0.35,
        w: 12.2,
        h: 0.8,
        fontSize: 27,
        bold: true,
        color: '1F2937'
      })
      const bullets = collectBullets(mainTopic)
      if (bullets.length) {
        slide.addText(bullets, {
          x: 0.75,
          y: 1.3,
          w: 11.8,
          h: 5.4,
          fontSize: 16,
          color: '334155',
          valign: 'top',
          breakLine: false
        })
      } else if (mainTopic.notes?.plain?.content) {
        slide.addText(mainTopic.notes.plain.content, {
          x: 0.75,
          y: 1.3,
          w: 11.8,
          h: 5.4,
          fontSize: 15,
          color: '475569',
          valign: 'top'
        })
      }
      if (workbook.sheets.length > 1) {
        slide.addText(sheet.title || '', {
          x: 0.55,
          y: 6.95,
          w: 12.2,
          h: 0.3,
          fontSize: 10,
          color: '94A3B8'
        })
      }
    }
  }

  const output = await pptx.write({ outputType: 'uint8array' })
  return toBytes(output)
}
