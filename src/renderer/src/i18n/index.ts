const dictionaries: Record<Language, Dict> = { 'zh-CN': zh, 'en-US': en }

export function translate(language: Language, key: string): string {
  return dictionaries[language]?.[key] ?? dictionaries['zh-CN'][key] ?? key
}

export function useT(): (key: string) => string {
  const language = useMapStore((s) => s.settings.language)
  return (key: string) => translate(language, key)
}
