import type { Theme } from '@shared/types'
import { part } from '@shared/defaults'

/**
 * Original theme presets for the renderer. Every preset is built from a small
 * palette so that all theme parts stay consistent while each preset keeps its
 * own character. No external theme assets are reused.
 */
export interface ThemePreset {
  id: string
  name: { zh: string; en: string }
  group: 'map' | 'logic' | 'org' | 'colorful' | 'dark'
  accent: string[]
  theme: Theme
}

const SANS = 'Inter, "PingFang SC", "Microsoft YaHei", system-ui, sans-serif'
const HUMANIST = '"Avenir Next", "PingFang SC", "Microsoft YaHei", system-ui, sans-serif'
const ROUNDED = '"Nunito", "Avenir Next", "PingFang SC", sans-serif'
const SERIF = '"Iowan Old Style", "Songti SC", Georgia, serif'
const MONO = '"JetBrains Mono", "SFMono-Regular", Menlo, monospace'

interface ThemePalette {
  font?: string
  mapFill: string
  centralFill: string
  centralText: string
  centralBorder?: string
  mainFill: string
  mainText: string
  subFill: string
  subText: string
  subBorder?: string
  line: string
  floatingFill: string
  floatingText: string
  summaryFill: string
  summaryText: string
  calloutFill: string
  calloutText: string
  importantFill: string
  importantText: string
  minorFill: string
  minorText: string
  boundaryLine: string
  relationshipLine?: string
  shapeClass?: string
  centralShapeClass?: string
  lineClass?: string
}

function tintOf(hex: string): string {
  return /^#[0-9a-f]{6}$/i.test(hex) ? `${hex}22` : hex
}

function buildTheme(id: string, p: ThemePalette): Theme {
  const font = p.font ?? SANS
  const shape = p.shapeClass ?? 'org.xmind.topicShape.roundedRect'
  const centralShape = p.centralShapeClass ?? shape
  const lineClass = p.lineClass ?? 'org.xmind.branchConnection.curve'
  const centralBorder = p.centralBorder ?? p.mainFill
  const subBorder = p.subBorder ?? p.line

  return {
    id: `theme-${id}`,
    centralTopic: part({
      'svg:fill': p.centralFill,
      'fo:color': p.centralText,
      'fo:font-family': font,
      'fo:font-size': '24pt',
      'fo:font-weight': 700,
      'border-line-color': centralBorder,
      'border-line-width': '2pt',
      'shape-class': centralShape
    }),
    mainTopic: part({
      'svg:fill': p.mainFill,
      'fo:color': p.mainText,
      'fo:font-family': font,
      'fo:font-size': '15pt',
      'fo:font-weight': 600,
      'border-line-color': p.mainFill,
      'border-line-width': '0pt',
      'shape-class': shape,
      'line-color': p.line,
      'line-width': '2pt',
      'line-class': lineClass
    }),
    subTopic: part({
      'svg:fill': p.subFill,
      'fo:color': p.subText,
      'fo:font-family': font,
      'fo:font-size': '12pt',
      'fo:font-weight': 500,
      'border-line-color': subBorder,
      'border-line-width': '1pt',
      'shape-class': shape,
      'line-color': p.line,
      'line-width': '2pt',
      'line-class': lineClass
    }),
    floatingTopic: part({
      'svg:fill': p.floatingFill,
      'fo:color': p.floatingText,
      'fo:font-family': font,
      'fo:font-size': '12pt',
      'fo:font-weight': 500,
      'border-line-color': p.floatingFill,
      'border-line-width': '1pt',
      'shape-class': shape
    }),
    summaryTopic: part({
      'svg:fill': p.summaryFill,
      'fo:color': p.summaryText,
      'fo:font-family': font,
      'fo:font-size': '11pt',
      'fo:font-weight': 600,
      'border-line-color': p.summaryText,
      'border-line-width': '1pt',
      'shape-class': shape
    }),
    calloutTopic: part({
      'svg:fill': p.calloutFill,
      'fo:color': p.calloutText,
      'fo:font-family': font,
      'fo:font-size': '11pt',
      'border-line-color': p.calloutText,
      'border-line-width': '1pt',
      'shape-class': shape
    }),
    importantTopic: part({
      'svg:fill': p.importantFill,
      'fo:color': p.importantText,
      'fo:font-family': font,
      'fo:font-size': '12pt',
      'fo:font-weight': 600,
      'border-line-color': p.importantText,
      'border-line-width': '1pt',
      'shape-class': shape
    }),
    minorTopic: part({
      'svg:fill': p.minorFill,
      'fo:color': p.minorText,
      'fo:font-family': font,
      'fo:font-size': '11pt',
      'border-line-color': p.minorFill,
      'border-line-width': '1pt',
      'shape-class': shape
    }),
    boundary: part({
      'border-line-color': p.boundaryLine,
      'border-line-width': '1pt',
      'svg:fill': tintOf(p.boundaryLine)
    }),
    summary: part({
      'border-line-color': p.summaryText,
      'line-color': p.summaryText,
      'line-width': '2pt',
      'line-class': 'org.xmind.relationship.curve'
    }),
    relationship: part({
      'line-color': p.relationshipLine ?? p.line,
      'line-width': '2pt',
      'line-class': 'org.xmind.relationship.curve'
    }),
    map: part({ 'svg:fill': p.mapFill }),
    colorThemeId: `${id}-color`,
    skeletonThemeId: 'default'
  }
}

function makePreset(
  number: number,
  zh: string,
  en: string,
  group: ThemePreset['group'],
  accent: string[],
  palette: ThemePalette
): ThemePreset {
  const id = `preset-${String(number).padStart(2, '0')}`
  return { id, name: { zh, en }, group, accent, theme: buildTheme(id, palette) }
}

